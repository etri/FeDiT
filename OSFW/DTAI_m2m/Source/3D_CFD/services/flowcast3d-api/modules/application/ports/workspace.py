from pathlib import Path
from typing import Any, BinaryIO, ContextManager, Iterable, Protocol

from modules.domain.schemas.flow import Grid


class WorkspaceCollection(Protocol):
    """원자적인 문서 갱신을 보존하는 Workspace 저장소 계약"""

    def find(self, *args: Any, **kwargs: Any) -> Any: ...
    def find_one(self, *args: Any, **kwargs: Any) -> dict[str, Any] | None: ...
    def insert_one(self, *args: Any, **kwargs: Any) -> Any: ...
    def update_one(self, *args: Any, **kwargs: Any) -> Any: ...
    def update_many(self, *args: Any, **kwargs: Any) -> Any: ...
    def replace_one(self, *args: Any, **kwargs: Any) -> Any: ...
    def delete_one(self, *args: Any, **kwargs: Any) -> Any: ...
    def find_one_and_update(self, *args: Any, **kwargs: Any) -> dict[str, Any] | None: ...


class WorkspaceAssets(Protocol):
    """등록된 원본과 파생 자산의 저장 및 회수 계약"""

    def save(self, path: Path, source: Path, *, metadata: dict[str, Any]) -> Any: ...
    def list(self, directory: Path) -> list[dict[str, Any]]: ...
    def delete(self, path: str | Path) -> None: ...


class WorkspaceFlow(Protocol):
    """Viewer의 결과 설명에 필요한 유동장 읽기 계약"""

    grid: Grid
    channels: list[str]
    attrs: dict[str, Any]
    history_frames: int
    n_frames: int

    def times(self) -> Iterable[float]: ...


class WorkspaceRepository(Protocol):
    """Workspace 기능이 사용하는 문서와 원본 저장소의 경계"""

    datasets: WorkspaceCollection
    tasks: WorkspaceCollection
    registrations: WorkspaceCollection
    scenarios: WorkspaceCollection
    result_contexts: WorkspaceCollection
    presentations: WorkspaceCollection
    space_counters: WorkspaceCollection
    sources: WorkspaceCollection
    assets: WorkspaceAssets

    def recover_incomplete(self) -> None: ...
    def completed_predictions(self) -> list[dict[str, Any]]: ...
    def prediction(
        self, identifier: str, *, completed: bool = False, projection: dict[str, Any] | None = None
    ) -> dict[str, Any] | None: ...
    def restore_prediction(
        self, record: dict[str, Any], identifier: str, target: Path, maximum_bytes: int
    ) -> None: ...
    def read_flow(self, path: str) -> WorkspaceFlow | None: ...
    def flow_grid(self, path: str) -> Grid: ...
    def store_revision(self, path: str) -> Any: ...
    def get_state(self) -> dict[str, Any]: ...
    def save_state(self, value: dict[str, Any]) -> None: ...


class WorkspaceUploads(Protocol):
    """업로드 소유권과 원본 등록 잠금을 제공하는 계약"""

    root: Path
    collection: WorkspaceCollection
    allowed_formats: frozenset[str]

    def lock(self, upload_id: str, *, blocking: bool = True, create: bool = True) -> ContextManager[bool]: ...
    def get(self, upload_id: str, owner: str, *, allow_expired: bool = False) -> dict[str, Any]: ...

    def create(self, length: int, header: str | None, owner: str) -> dict[str, Any]: ...
    def headers(self, document: dict[str, Any]) -> dict[str, str]: ...
    def open_patch(self, upload_id: str, owner: str, offset: int) -> tuple[dict[str, Any], BinaryIO]: ...
    def commit(
        self, document: dict[str, Any], stream: BinaryIO, received: int, checksum: str | None
    ) -> dict[str, Any]: ...
    def cancel(self, upload_id: str, owner: str) -> None: ...
    def prune_expired(self, dry_run: bool = False) -> dict[str, int]: ...
    def identity(self, upload_id: str, owner: str) -> dict[str, Any]: ...
