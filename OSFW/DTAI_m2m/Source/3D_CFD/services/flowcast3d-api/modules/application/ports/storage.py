"""유동장과 형상 저장소 접근 계약"""

from pathlib import Path
from typing import Any, Protocol


class FlowStorage(Protocol):
    """관리 기능이 사용하는 저장소 연산"""

    def read(self, path: str | Path) -> Any: ...
    def exists(self, path: str | Path) -> bool: ...
    def attrs(self, path: str | Path) -> dict: ...
    def list(self, prefix: str | Path) -> list[str]: ...
    def mapping(self, path: str | Path) -> Any: ...
    def create(self, path: str | Path, metadata: Any, **options: Any) -> Any: ...
    def rename(self, source: str | Path, destination: str | Path) -> None: ...
    def copy(self, source: str | Path, destination: str | Path) -> None: ...
