package kr.co.n2m.platform.admin.feature.menu.query;

import java.util.List;

import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;

import kr.co.n2m.platform.admin.feature.menu.entity.Menu;
import kr.co.n2m.platform.common.entity.CamelCaseMap;

public interface MenuRepository extends JpaRepository<Menu, String> {

	@Query(nativeQuery = true, value=""
			+ "select "
			+ "       icommenu.menu_oid"
			+ "     , icommenu.menu_id"
			+ "     , icommenu.menu_nm"
			+ "     , icommenu.up_menu_oid"
			+ "     , icommenu.menu_desc"
			+ "     , icommenu.menu_tgt_cd"
			+ "     , icommenu.use_yn"
			+ "     , icommenu.url"
			+ "     , icommenu.url_param"
			+ "     , icommenu.type_cd"
			+ "     , icommenu.pltfrm_id"
			+ "     , icomplatform.odrg as pltfrm_odrg "
			+ "     , icommenu.odrg"
			+ "     , icommenu.popup_yn"
			+ "     , icommenu.popup_wdth"
			+ "     , icommenu.popup_hght"
			+ "     , icommenu.menu_icon"
			+ "     , icommenu.reg_dt"
			+ "     , icommenu.regr_id"
			+ "     , icommenu.regr_nm"
			+ "     , icommenu.amd_dt"
			+ "     , icommenu.amdr_id"
			+ "     , icommenu.amdr_nm"
			+ "     , icommenu.admr_yn"
			+ "     , imenuauth.read_yn"
			+ "     , imenuauth.write_yn"
			+ "     , imenuauth. amd_yn"
			+ "     , imenuauth.del_yn"
			+ "  from common.tb_com_menu icommenu"
			+ "       left outer join (select icomauthmenumap.menu_oid"
			+ "                             , (case when sum(case when icomauthmenumap.read_yn = 'Y' then 1 else 0 end) = 0 then 'N' else 'Y' end) as read_yn"
			+ "                             , (case when sum(case when icomauthmenumap.write_yn = 'Y' then 1 else 0 end) = 0 then 'N' else 'Y' end) as write_yn"
			+ "                             , (case when sum(case when icomauthmenumap.amd_yn = 'Y' then 1 else 0 end) = 0 then 'N' else 'Y' end) as amd_yn"
			+ "                             , (case when sum(case when icomauthmenumap.del_yn = 'Y' then 1 else 0 end) = 0 then 'N' else 'Y' end) as del_yn"
			+ "                          from common.tb_com_authmenumap icomauthmenumap"
			+ "                         where icomauthmenumap.aut_oid in (select icomauthusermap.aut_oid"
			+ "       		                                                from common.tb_com_authusermap icomauthusermap"
			+ "       		                                               where icomauthusermap.user_id = :userId"
			+ "       		                                               group by icomauthusermap.aut_oid"
			+ "                                                            UNION "
			+ "       		                                              SELECT iauth.aut_oid"
			+ "       		                                                FROM common.tb_com_auth iauth"
			+ "       		                                               WHERE iauth.aut_id IN (:defaultAutOidList)"
			+ "       		                                                 AND iauth.use_yn = 'Y'"
			+ "                                                           )"
			+ "                         group by menu_oid"
			+ "                       ) imenuauth on imenuauth.menu_oid = icommenu.menu_oid"
			+ "       left outer join common.tb_com_platform icomplatform  on icomplatform.pltfrm_id = icommenu.pltfrm_id and icomplatform.use_yn = 'Y'"
			+ " where imenuauth.menu_oid is not null "
			+ "   and icommenu.use_yn = 'Y'"
			+ "   and (icommenu.pltfrm_id = cast(:pltfrmId as text) or :pltfrmId is null) "
			+ "   and (icommenu.admr_Yn = cast(:admrYn as text) or :admrYn is null) "
			+ "   and (icommenu.type_cd = cast(:typeCd as text) or :typeCd is null) "
			+ "   and (imenuauth.read_yn = cast(:readYn as text) or :readYn is null) "
			+ " order by icomplatform.odrg"
			+ "        , icommenu.odrg"
	)
	List<CamelCaseMap> getUserMenu(@Param("userId") String userId, @Param("pltfrmId") String pltfrmId, @Param("admrYn") String admrYn, @Param("typeCd") String typeCd, @Param("readYn") String readYn, @Param("defaultAutOidList") List<String> defaultAutOidList);

	@Query(nativeQuery = true, value=""
			+ "select *"
			+ "  from (select icommenu.menu_oid"
			+ "             , icommenu.menu_id"
			+ "             , icommenu.menu_nm"
			+ "             , icommenu.up_menu_oid"
			+ "             , icommenu.menu_desc"
			+ "             , icommenu.menu_tgt_cd"
			+ "             , icommenu.use_yn"
			+ "             , icommenu.url"
			+ "             , icommenu.url_param"
			+ "             , icommenu.type_cd"
			+ "             , icommenu.pltfrm_id"
			+ "             , icomplatform.odrg as pltfrm_odrg" 
			+ "             , icommenu.odrg"
			+ "             , icommenu.popup_yn"
			+ "             , icommenu.popup_wdth"
			+ "             , icommenu.popup_hght"
			+ "             , icommenu.menu_icon"
			+ "             , icommenu.reg_dt"
			+ "             , icommenu.regr_id"
			+ "             , icommenu.regr_nm"
			+ "             , icommenu.amd_dt"
			+ "             , icommenu.amdr_id"
			+ "             , icommenu.amdr_nm"
			+ "             , icommenu.admr_yn"
			+ "             , icomauthmenumap.aut_oid"
			+ "             , (case when sum(case when icomauthmenumap.read_yn  = 'Y' then 1 else 0 end) = 0 then 'N' else 'Y' end) as read_yn"
			+ "             , (case when sum(case when icomauthmenumap.write_yn = 'Y' then 1 else 0 end) = 0 then 'N' else 'Y' end) as write_yn"
			+ "             , (case when sum(case when icomauthmenumap.amd_yn   = 'Y' then 1 else 0 end) = 0 then 'N' else 'Y' end) as amd_yn"
			+ "             , (case when sum(case when icomauthmenumap.del_yn   = 'Y' then 1 else 0 end) = 0 then 'N' else 'Y' end) as del_yn"
			+ "          from common.tb_com_menu icommenu "
			+ "               inner join common.tb_com_authmenumap icomauthmenumap on icomauthmenumap.menu_oid = icommenu.menu_oid "
			+ "               left outer join common.tb_com_platform icomplatform on icomplatform.pltfrm_id = icommenu.pltfrm_id and icomplatform.use_yn = 'Y' "
			+ "         where icomauthmenumap.aut_oid in (select icomauthusermap.aut_oid "
			+ "                                          from common.tb_com_authusermap icomauthusermap "
			+ "                                         where icomauthusermap.user_id = :userId "
			+ "                                         group by icomauthusermap.aut_oid) "
			+ "           and icommenu.use_yn = 'Y' "
			+ "           and (icommenu.pltfrm_id = cast(:pltfrmId as text) or :pltfrmId is null) "
			+ "           and (icommenu.admr_Yn = cast(:admrYn as text) or :admrYn is null) "
			+ "           and (icommenu.type_cd = cast(:typeCd as text) or :typeCd is null) "
			+ "         group by icommenu.menu_oid, icommenu.menu_id, icomauthmenumap.aut_oid, icomplatform.odrg"
			+ "       ) menu"
			+ " order by pltfrm_odrg, odrg"
	)
	List<CamelCaseMap> getUserMenuOld(@Param("userId") String userId, @Param("pltfrmId") String pltfrmId, @Param("admrYn") String admrYn, @Param("typeCd") String typeCd);

	@Query(nativeQuery = true, value=""
			+ "select "
			+ "       icommenu.menu_oid"
			+ "     , icommenu.menu_id"
			+ "     , icommenu.menu_nm"
			+ "     , icommenu.up_menu_oid"
			+ "     , icommenu.menu_desc"
			+ "     , icommenu.menu_tgt_cd"
			+ "     , icommenu.use_yn"
			+ "     , icommenu.url"
			+ "     , icommenu.url_param"
			+ "     , icommenu.type_cd"
			+ "     , icommenu.pltfrm_id"
			+ "     , icomplatform.odrg as pltfrm_odrg "
			+ "     , icommenu.odrg"
			+ "     , icommenu.popup_yn"
			+ "     , icommenu.popup_wdth"
			+ "     , icommenu.popup_hght"
			+ "     , icommenu.menu_icon"
			+ "     , icommenu.reg_dt"
			+ "     , icommenu.regr_id"
			+ "     , icommenu.regr_nm"
			+ "     , icommenu.amd_dt"
			+ "     , icommenu.amdr_id"
			+ "     , icommenu.amdr_nm"
			+ "     , icommenu.admr_yn"
			+ "     , 'Y' as read_yn"
			+ "     , 'Y' as write_yn"
			+ "     , 'Y' as amd_yn"
			+ "     , 'Y' as del_yn"
			+ "  from common.tb_com_menu icommenu"
			+ "       left outer join common.tb_com_platform icomplatform  on icomplatform.pltfrm_id = icommenu.pltfrm_id and icomplatform.use_yn = 'Y'"
			+ " where icommenu.use_yn = 'Y'"
			+ "   and (icommenu.pltfrm_id = cast(:pltfrmId as text) or :pltfrmId is null) "
			+ "   and (icommenu.admr_Yn = cast(:admrYn as text) or :admrYn is null) "
			+ "   and (icommenu.type_cd = cast(:typeCd as text) or :typeCd is null) "
			+ "   and ('Y' = case when :readYn is null then 'Y' else :readYn end) "
			+ " order by icomplatform.odrg"
			+ "        , icommenu.odrg"
	)
	List<CamelCaseMap> getSuperUser(@Param("pltfrmId") String pltfrmId, @Param("admrYn") String admrYn, @Param("typeCd") String typeCd, @Param("readYn") String readYn);
}
