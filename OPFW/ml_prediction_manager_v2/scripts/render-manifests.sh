#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
ENV_FILE="${1:-${PROJECT_ROOT}/.env}"
TEMPLATE_FILE="${PROJECT_ROOT}/k8s/deployment.yaml.template"
OUTPUT_FILE="${PROJECT_ROOT}/k8s/deployment.yaml"

if ! command -v envsubst >/dev/null 2>&1; then
  echo "envsubst 명령이 없습니다. Ubuntu 기준 gettext-base 패키지를 설치하세요." >&2
  exit 1
fi

if [ ! -f "${ENV_FILE}" ]; then
  echo ".env 파일이 없습니다: ${ENV_FILE}" >&2
  echo "먼저 cp ${PROJECT_ROOT}/.env.example ${PROJECT_ROOT}/.env 후 운영 값을 수정하세요." >&2
  exit 1
fi

set -a
# shellcheck disable=SC1090
source "${ENV_FILE}"
set +a

: "${REGISTRY_HOST:?REGISTRY_HOST is required}"
: "${PM_IMAGE_TAG:?PM_IMAGE_TAG is required}"
: "${DEFAULT_NAMESPACE:?DEFAULT_NAMESPACE is required}"
: "${KUBEFLOW_URL:?KUBEFLOW_URL is required}"

: "${REGISTRY_URL:=http://${REGISTRY_HOST}}"
: "${MLFLOW_IMAGE_TAG:=mlflow-postgres:v3.11.1-pg}"
: "${PM_TENANT_IMAGE_REGISTRY:=${REGISTRY_HOST}}"
: "${PM_TENANT_MLFLOW_IMAGE:=${PM_TENANT_IMAGE_REGISTRY}/${MLFLOW_IMAGE_TAG}}"
: "${PM_TENANT_RAY_IMAGE:=${PM_TENANT_IMAGE_REGISTRY}/ray-mlflow:2.54.1}"
: "${PM_TENANT_NIFI_IMAGE:=${PM_TENANT_IMAGE_REGISTRY}/prediction-manager-nifi-python:1.28.1-pm2}"
: "${PM_TENANT_NIFI_RUN_AS_USER:=1000}"
: "${PM_TENANT_NIFI_RUN_AS_GROUP:=1000}"
: "${PM_TENANT_NIFI_FS_GROUP:=1000}"
: "${PM_PROVISIONER_IMAGE:=${PM_TENANT_IMAGE_REGISTRY}/${PM_IMAGE_TAG}}"
: "${DATASET_INTERNAL_BASE_URL:=http://prediction-manager.kubeflow.svc.cluster.local}"
: "${FEEDBACK_DATASET_INTERNAL_BASE_URL:=${DATASET_INTERNAL_BASE_URL}}"
: "${LABEL_STUDIO_URL:=http://label-studio.kubeflow.svc.cluster.local}"
: "${LABEL_STUDIO_API_TOKEN:=}"
: "${ADMIN_EMAILS:=admin@example.com}"
: "${PM_TENANT_STORAGE_CLASS:=}"
: "${PM_TENANT_MLFLOW_STORAGE_CLASS:=}"
: "${PM_TENANT_NIFI_STORAGE_CLASS:=}"
: "${PM_JUPYTER_CONFIGMAP_NAME:=}"
: "${PM_JUPYTER_CONFIGMAP_NAMESPACE:=kubeflow}"
: "${PM_JUPYTER_WEB_APP_DEPLOYMENT:=jupyter-web-app-deployment}"
: "${MODEL_STORE_ROOT:=/models}"
: "${MODEL_STORE_BACKEND:=pvc}"
: "${DATASET_STORE_ROOT:=/datasets}"
: "${DOCKER_SOCKET:=unix:///var/run/docker.sock}"

export REGISTRY_URL REGISTRY_HOST PM_IMAGE_TAG DEFAULT_NAMESPACE KUBEFLOW_URL
export MODEL_STORE_ROOT MODEL_STORE_BACKEND DATASET_STORE_ROOT DATASET_INTERNAL_BASE_URL FEEDBACK_DATASET_INTERNAL_BASE_URL ADMIN_EMAILS
export LABEL_STUDIO_URL LABEL_STUDIO_API_TOKEN
export PM_TENANT_STORAGE_CLASS PM_TENANT_MLFLOW_STORAGE_CLASS PM_TENANT_NIFI_STORAGE_CLASS
export PM_JUPYTER_CONFIGMAP_NAME PM_JUPYTER_CONFIGMAP_NAMESPACE PM_JUPYTER_WEB_APP_DEPLOYMENT
export PM_TENANT_IMAGE_REGISTRY PM_TENANT_MLFLOW_IMAGE PM_TENANT_RAY_IMAGE PM_TENANT_NIFI_IMAGE PM_PROVISIONER_IMAGE
export PM_TENANT_NIFI_RUN_AS_USER PM_TENANT_NIFI_RUN_AS_GROUP PM_TENANT_NIFI_FS_GROUP
export DOCKER_SOCKET

envsubst < "${TEMPLATE_FILE}" > "${OUTPUT_FILE}"
echo "rendered: ${OUTPUT_FILE}"
